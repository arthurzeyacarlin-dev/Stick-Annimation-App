# SPEC-0020 Phase 3: generate app/themes.css — every accent recolors the whole app (Dark), and Bright mode is the
# light version of that accent. Diamond blue + Dark keeps the original hex values exactly (no override).
import colorsys, sys, re, pathlib
CORE = {  # token: default (Dark, Diamond blue)
  "page": "030914", "panel": "071120", "line": "163058", "border": "244267", "selected-bg": "0f2a52",
  "selected-border": "3a6aa3", "text": "f6f9ff", "text-2": "c9d6ea", "text-3": "a8bddd", "muted": "8fabd0",
  "label": "7895bc", "link": "8cbbf3", "focus": "66c7ff", "icon": "7296bd", "on-selected": "eaf3ff",
}
EXTRA = ["6f8db4","3a5a85","2f86ff","58aaff","376a9e","2b4f7d","103f82","1764ae","48cee7","278bc5","123f7a","9ccaff",
         "a9eeff","5bb8ff","2a7be4","408eff","507caf","abcdfc","8aa4c5","6b86a9","3d8bff"]
VIVID = {"blue": "0066ff", "purple": "7c3aed", "green": "12a150", "orange": "ef6c1a", "pink": "e0408a", "red": "e5384a", "teal": "0f9b9b"}
BASE_HUE = 216 / 360

def hls(h): return colorsys.rgb_to_hls(*(int(h[i:i+2], 16) / 255 for i in (0, 2, 4)))
def hexof(H, L, S):
    r, g, b = colorsys.hls_to_rgb(H % 1, max(0, min(1, L)), max(0, min(1, S)))
    return "#%02x%02x%02x" % tuple(round(c * 255) for c in (r, g, b))
def shifted(h, hue):
    H, L, S = hls(h); return hexof(hue + (H - BASE_HUE), L, S)
def darker(h, amount):
    H, L, S = hls(h); return hexof(H, L - amount, S)

out = ["/* SPEC-0020 Phase 3 — generated by palettes.py. Settings → Appearance: every accent recolors the whole app;",
       "   Bright mode is the light version of the accent. Diamond blue + Dark = the original colors (in globals.css). */",
       ":root {"]
out += [f"  --da-c-{h}: #{h};" for h in EXTRA]
out += ["  --da-on-selected: #eaf3ff;", "  --da-logo-tile: #071120;", "}"]
for name, vivid in VIVID.items():
    hue = hls(vivid)[0]
    if name != "blue":
        out.append(f'html[data-accent="{name}"] {{')
        out += [f"  --da-{t}: {shifted(v, hue)};" for t, v in CORE.items()]
        out += [f"  --da-c-{h}: {shifted(h, hue)};" for h in EXTRA]
        out += [f"  --da-hover: #{vivid};", f"  --da-logo-tile: {shifted('071120', hue)};", "}"]
    sel = 'html[data-theme="light"]' + ("" if name == "blue" else f'[data-accent="{name}"]')
    S = lambda s, l: hexof(hue, l, s)
    light = {
      "page": S(.45, .955), "panel": S(.60, .995), "line": S(.35, .88), "border": S(.32, .79),
      # Arthur: in Bright mode the top bar is a darker shade of the accent, so the white logo sits right on it (no tile).
      "header": S(.30, .36), "header-line": S(.30, .28), "header-sub": S(.45, .84), "header-hover": S(1.0, .72),
      "selected-bg": darker(vivid, .06), "selected-border": "#" + vivid, "hover": "#" + vivid,
      "text": S(.50, .10), "text-2": S(.30, .22), "text-3": S(.22, .32), "muted": S(.18, .42), "label": S(.20, .48),
      "link": darker(vivid, .10), "focus": "#" + vivid, "icon": S(.35, .45), "on-selected": "#ffffff",
      "danger": "#c62f3d", "logo-tile": shifted("071120", hue),
    }
    out.append(sel + " {")
    out += [f"  --da-{t}: {v};" for t, v in light.items()]
    for h in EXTRA:
        H, L, Sx = hls(h)
        out.append(f"  --da-c-{h}: {hexof(hue + (H - BASE_HUE), max(.10, min(.96, 1 - L)), Sx * .8)};")
    out += ["  --da-scrim: rgba(12, 24, 48, 0.35);", "  --da-shadow-pop: 0 18px 44px rgba(15, 30, 60, 0.18);", "  color-scheme: light;", "}"]
pathlib.Path(sys.argv[1]).write_text("\n".join(out) + "\n")
print("wrote", sys.argv[1], len(out), "lines")
